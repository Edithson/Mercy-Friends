export function t(key, replacements = {}) {
    const loc = getLocale();
    const dict = I18N_STRINGS[loc] || I18N_STRINGS.en;
    let text = dict[key] || I18N_STRINGS.en[key] || key;
    for (const [k, v] of Object.entries(replacements)) {
        text = text.replace(new RegExp(`:${k}`, 'g'), v);
    }
    return text;
}

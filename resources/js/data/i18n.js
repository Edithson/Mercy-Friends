export function getLocale() {
    const docLocale = document.documentElement.lang;
    const winLocale = window.APP_LOCALE;
    const loc = (winLocale || docLocale || 'en').toLowerCase().substring(0, 2);
    return ['en', 'fr', 'de'].includes(loc) ? loc : 'en';
}

